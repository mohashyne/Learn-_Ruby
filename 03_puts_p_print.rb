# auto line break if you use puts
puts "Hello World!"
puts "I'm alive and well!"

# line  break and shows type
p "Hello String!"
p "I'm alive and well!"

# no line break
print "Hello World!"
print "I'm alive and Okay!"
puts

puts 4 + 5
p 4 + 5

# concatinate
puts "4" + "4"
p "4" + "4"

# "p" offers  and additional clearity  on how things operate, and a visual indicator

puts "Hi this is a
big line break"

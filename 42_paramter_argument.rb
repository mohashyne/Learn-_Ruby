#  name and age is the parameter and what
# the user inputs when the method is called, is the argument
def sum(name, age)
  puts "his name is #{name}  and  #{age}years old"
  puts "he is #{name}"
  puts "he is #{age} years old"
end

sum("hassan", 22) # hassan and 22 are the arguments
# result:
# his name is hassan  and  22years old
# he is hassan
# he is 22 years old


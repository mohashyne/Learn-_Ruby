# Arrays
# An array is a data structure that contains a collection of elements,
# typically of the same type, stored in a contiguous block of memory.
# Each element in an array is accessed using an index,
# which is an integer that represents the element's position within the array.
# Arrays are widely used in programming because they provide efficient means to store and access multiple values.
# Key Characteristics of Arrays:
#
#     Fixed Size:
#         The size of an array is defined when it is created and cannot be changed.
# This means the number of elements it can hold is fixed.
#
#     Indexed Access:
#         Elements in an array are accessed using indices,
# which usually start from 0 in most programming languages (like C, Java, Python, Ruby).
#
#     Homogeneous Elements:
#         Arrays typically store elements of the same data type (e.g., all integers, all floats, all strings).
#
#     Contiguous Memory:
#         Elements are stored in contiguous memory locations, which allows for efficient access and manipulation.

